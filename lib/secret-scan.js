// `scripts/secret_scan.py` — the Secret gate's helper script.
//
// The gate the course teaches is a pipeline, and IR only holds argv lists:
//
//   git ls-files -z | xargs -0 uv run --locked detect-secrets-hook --baseline .secrets.baseline
//
// Windows has no `xargs`, so the same gate has to be one program that builds the
// argv list itself: a full scan over `git ls-files -z` for CI, and a staged-only
// scan over `git diff --staged --name-only --diff-filter=ACM -z` for the commit
// hook. The generated script is stdlib-only, so it runs wherever Python does.
//
// Two printed lines are a contract with `py-pipeline-run.failureKind()`:
// "No such file or directory: .secrets.baseline" and "detect-secrets is not
// recognized: 请先 uv sync --locked --all-groups". Both mean the gate never got
// to judge anything (`environment`), not that it found a secret (`findings`), so
// neither wording may drift.
//
// The hook entry that runs `--staged` lives in `prek.js`; the CI step that runs
// the full scan lives in the `ir.js` security stage.

/** Where the generated helper belongs in the user's project. */
