/**
 * `.pre-commit-config.yaml` for prek, rendered from the modern-python skill.
 *
 * prek is a drop-in replacement for pre-commit: same file format, same hook ids,
 * `prek install` / `prek run --all-files` instead of the pre-commit verbs.
 *
 * v0.10 changes two things about the file the skill ships:
 *
 * 1. `Yelp/detect-secrets` is no longer a remote hook. The project pins
 *    `detect-secrets` in its own `security` dependency group and runs it through
 *    `scripts/secret_scan.py`, so a remote hook would install a *second* copy of
 *    the same scanner, at a version `uv.lock` has never seen, whose findings could
 *    disagree with the CI gate. One scanner, one version, one verdict.
 * 2. Two `repo: local` hooks run this repository's own commit profile and staged
 *    secret scan through `uv run --locked`. A hand-kept hook list is a second
 *    definition of "what a commit must pass"; the profile is the first one, and
 *    local hooks make the two the same file.
 *
 * The `<latest>` rev convention still comes from the skill: it explicitly says to
 * replace those placeholders rather than invent tags, and inventing a tag here
 * would produce a file that pins a version that may not exist.
 *
 * @module
 */

/**
 * Hooks whose `rev` cannot be known offline.
 *
 * Each entry carries the releases URL the skill prints next to the placeholder,
 * so the caller has one place to look up all of them. `Yelp/detect-secrets` is
 * absent on purpose (see the module comment): it is a local hook now, and a
 * placeholder rev for a hook that is not rendered would be a dead link.
 */
export const PLACEHOLDER_REVS = [
  { repo: 'astral-sh/ruff-pre-commit', url: 'https://github.com/astral-sh/ruff-pre-commit/releases' },
  { repo: 'koalaman/shellcheck-precommit', url: 'https://github.com/koalaman/shellcheck-precommit/tags' },
  { repo: 'rhysd/actionlint', url: 'https://github.com/rhysd/actionlint/releases' },
  { repo: 'zizmorcore/zizmor-pre-commit', url: 'https://github.com/zizmorcore/zizmor-pre-commit/releases' },
]

/** The Python the hooks' own environments use, as `python3.12`-style text. */
function languageVersion(pythonVersion) {
  const value = typeof pythonVersion === 'string' && /^\d+\.\d+$/.test(pythonVersion.trim())
    ? pythonVersion.trim()
    : '3.12'
  return 'python' + value
}

/**
 * Render the config.
 *
 * @param {object} [options]
 * @param {string} [options.pythonVersion] `3.12`-style; defaults to 3.12, the
 *   skill template's own default.
 * @param {boolean} [options.includeBuiltin] the `repo: builtin` file checks.
 * @param {boolean} [options.includeSecurity] the three non-Python security hooks
 *   (shellcheck / actionlint / zizmor). Off by default in v0.10: the credential
 *   scan they used to include is a local hook now, so "security hooks" is no
 *   longer one yes/no switch that the local repo inherits.
 * @returns {string} YAML text, newline-terminated.
 */
export function renderPreCommitConfig(options = {}) {
  const includeBuiltin = options.includeBuiltin !== false
  const includeSecurity = options.includeSecurity === true
  const lines = []

  lines.push('# .pre-commit-config.yaml — prek reads the same format as pre-commit.')
  lines.push('# Generated by gatekeeper from the 2-modern-python skill.')
  // The renderer describes the file, not what the caller does with it: this same
  // string is what `py-apply` writes to disk, and "nothing was written" would then
  // be a lie sitting inside the file it just wrote.
  lines.push('#')
  lines.push('# `rev: "<latest>"` is the skill\'s own placeholder convention.')
  lines.push('# Replace each one with a release tag, or run `prek auto-update --cooldown-days 7`.')
  lines.push('#')
  lines.push('# The two `repo: local` hooks at the bottom run this repository\'s own commit')
  lines.push('# profile, so a hook run, a laptop run and CI execute the same stage list instead')
  lines.push('# of a hand-kept copy of it.')
  lines.push('')
  lines.push('default_language_version:')
  lines.push('  python: ' + languageVersion(options.pythonVersion))
  lines.push('')
  lines.push('repos:')

  lines.push('  # Ruff — linting and formatting; replaces black, isort, flake8, pylint.')
  lines.push('  - repo: https://github.com/astral-sh/ruff-pre-commit')
  lines.push('    rev: "<latest>"  # https://github.com/astral-sh/ruff-pre-commit/releases')
  lines.push('    hooks:')
  lines.push('      - id: ruff')
  lines.push('        args: [--fix]')
  lines.push('      - id: ruff-format')

  if (includeBuiltin) {
    lines.push('')
    lines.push('  # prek builtin hooks — Rust-native, no external repos to clone.')
    lines.push('  - repo: builtin')
    lines.push('    hooks:')
    lines.push('      - id: trailing-whitespace')
    lines.push('      - id: end-of-file-fixer')
    lines.push('      - id: check-yaml')
    lines.push('      - id: check-toml')
    lines.push('      - id: check-merge-conflict')
  }

  if (includeSecurity) {
    lines.push('')
    lines.push('  # Security hooks that are not Python, so they cannot come from uv.lock.')
    lines.push('  # The credential scan is deliberately NOT here: it runs from the project\'s')
    lines.push('  # locked detection tooling in the `repo: local` section below.')
    lines.push('  - repo: https://github.com/koalaman/shellcheck-precommit')
    lines.push('    rev: "<latest>"  # https://github.com/koalaman/shellcheck-precommit/tags')
    lines.push('    hooks:')
    lines.push('      - id: shellcheck')
    lines.push('        args: [--severity=error]')
    lines.push('')
    lines.push('  - repo: https://github.com/rhysd/actionlint')
    lines.push('    rev: "<latest>"  # https://github.com/rhysd/actionlint/releases')
    lines.push('    hooks:')
    lines.push('      - id: actionlint')
    lines.push('')
    lines.push('  - repo: https://github.com/zizmorcore/zizmor-pre-commit')
    lines.push('    rev: "<latest>"  # https://github.com/zizmorcore/zizmor-pre-commit/releases')
    lines.push('    hooks:')
    lines.push('      - id: zizmor')
    lines.push('        args: [--persona=regular, --min-severity=medium, --min-confidence=medium]')
  }

  lines.push('')
  lines.push('  # The repository\'s own gates, through uv so the hook and CI use one locked')
  lines.push('  # toolchain. `pass_filenames: false`: the profile selects its own stages and')
  lines.push('  # files, and a hook-filtered file list would quietly make it weaker than CI.')
  lines.push('  # `always_run: true`: a commit that touches nothing a hook matches must still')
  lines.push('  # run the gate instead of reporting success by skipping it.')
  lines.push('  - repo: local')
  lines.push('    hooks:')
  lines.push('      - id: gatekeeper')
  lines.push('        name: gatekeeper (commit profile)')
  lines.push('        entry: uv run --locked python scripts/ci.py --profile commit')
  lines.push('        language: system')
  lines.push('        pass_filenames: false')
  lines.push('        always_run: true')
  lines.push('      - id: gatekeeper-secrets')
  lines.push('        name: gatekeeper (secrets, staged)')
  lines.push('        entry: uv run --locked python scripts/secret_scan.py --staged')
  lines.push('        language: system')
  lines.push('        pass_filenames: false')
  lines.push('        always_run: true')

  return lines.join('\n') + '\n'
}

/**
 * The commands that turn the file into a working hook installation.
 *
 * Order matters: prek has to exist, the hooks have to be installed, and the
 * secrets baseline has to be created and *audited* before the local
 * `gatekeeper-secrets` hook can pass. The baseline is a file with a human audit
 * trail, not just scanner output, so the last step is a warning as much as a
 * command: `>` overwrites that trail, `--baseline` updates it in place.
 */
export function prekNextSteps({ includeSecurity = true } = {}) {
  const steps = [
    'uv tool install prek',
    'prek install',
    'prek run --all-files',
  ]
  // The baseline step is unconditional: the local `gatekeeper-secrets` hook is
  // rendered whether or not the three remote security hooks are, and it cannot
  // pass without the baseline. `includeSecurity` stays in the signature because
  // `py-prek` already passes it; it only ever controlled the remote hooks.
  steps.push(
    'Create and audit .secrets.baseline once: `uv run --locked detect-secrets scan > .secrets.baseline`, '
    + 'then `uv run --locked detect-secrets audit .secrets.baseline`. After that never overwrite it with '
    + '`>` (that discards the audit trail) — record reviewed findings in place with '
    + '`uv run --locked detect-secrets scan --baseline .secrets.baseline`.',
  )
  return steps
}

/** Why each stanza is there, for the tool's `rationale`. */
export function prekRationale(options = {}) {
  const includeBuiltin = options.includeBuiltin !== false
  const includeSecurity = options.includeSecurity === true
  const rationale = [
    'prek is a Rust-native drop-in for pre-commit: the same `.pre-commit-config.yaml`, '
    + '~7x faster installs, and it uses uv for Python toolchains instead of managing its own.',
    'Ruff replaces black, isort, flake8 and pylint in one hook; `--fix` lets it repair what it can '
    + 'so the hook fails only on what a human has to decide.',
  ]
  if (includeBuiltin) {
    rationale.push(
      'the `repo: builtin` hooks are prek\'s Rust implementations, so the common file checks cost '
      + 'no clone and work offline.',
    )
  }
  rationale.push(
    'the two `repo: local` hooks run the commit profile (`scripts/ci.py --profile commit`) and the '
    + 'staged secret scan (`scripts/secret_scan.py --staged`) through `uv run --locked`: the same '
    + 'stages, in the same order, with the versions uv.lock pins. That is the reason they live in '
    + 'this file instead of a second list of commands in the README.',
    '`gatekeeper-secrets` scans only staged files (`--staged`) so a credential cannot be committed '
    + 'before the CI scan ever sees the branch; the full-tree scan stays the security gate\'s job, '
    + 'because that one runs with the toolchain installed and can fail the build.',
  )
  if (includeSecurity) {
    rationale.push(
      'the three security hooks that stay remote are the ones that are not Python: shellcheck for '
      + 'shell bugs, actionlint for workflow syntax, zizmor for workflow permissions and injection '
      + 'risks. detect-secrets is not among them any more — it comes from this project\'s `security` '
      + 'dependency group through the local hook, so the hook and CI use one version of the scanner '
      + 'instead of two that can disagree about the same file.',
    )
  } else {
    rationale.push(
      'detect-secrets is absent from the remote hooks either way: the local `gatekeeper-secrets` '
      + 'hook runs the project-locked scanner, which is the only definition of "a secret" this '
      + 'repository has.',
    )
  }
  rationale.push(
    'every `rev` is a placeholder on purpose — the skill says to check the releases page rather than '
    + 'pin a version that may not exist.',
  )
  return rationale
}
