/**
 * `.github/dependabot.yml`, rendered from the modern-python skill.
 *
 * Source: `modern-python/templates/dependabot.yml` plus `references/dependabot.md`
 * and `references/security-setup.md`. The two numbers that matter are the weekly
 * interval and the 7-day cooldown — the cooldown is the supply-chain protection
 * the skill explains at length, so it is a default here, not an option a caller
 * has to know about.
 *
 * @module
 */

/** The ecosystems the skill's template configures. */
const DEFAULT_ECOSYSTEMS = ['pip', 'github-actions']

/** `daily` / `weekly` / `monthly` — the only values GitHub accepts. */
const INTERVALS = ['daily', 'weekly', 'monthly']

/**
 * Render the config.
 *
 * @param {object} [options]
 * @param {string} [options.schedule] `daily` | `weekly` | `monthly`.
 * @param {string} [options.directory] ecosystem directory; `/` by default.
 * @param {string[]} [options.ecosystems] subset of `pip`, `github-actions`.
 * @param {number} [options.cooldownDays] `cooldown.default-days`; 7 by default.
 * @param {boolean} [options.includeGrouping] group minor/patch updates.
 * @returns {string} YAML text, newline-terminated.
 */
export function renderDependabotConfig(options = {}) {
  const schedule = INTERVALS.includes(options.schedule) ? options.schedule : 'weekly'
  const directory = typeof options.directory === 'string' && options.directory.trim() !== ''
    ? options.directory.trim()
    : '/'
  const cooldown = Number.isInteger(options.cooldownDays) && options.cooldownDays >= 0
    ? options.cooldownDays
    : 7
  const includeGrouping = options.includeGrouping !== false
  const requested = Array.isArray(options.ecosystems) && options.ecosystems.length > 0
    ? options.ecosystems
    : DEFAULT_ECOSYSTEMS
  const ecosystems = requested.filter((entry) => DEFAULT_ECOSYSTEMS.includes(entry))
  const effective = ecosystems.length > 0 ? ecosystems : DEFAULT_ECOSYSTEMS

  const lines = []
  lines.push('# .github/dependabot.yml — generated by gatekeeper.')
  lines.push('# Source: 2-modern-python (references/dependabot.md, security-setup.md).')
  // Describes the file only. `py-apply` writes this same text to disk, so a
  // "nothing was written" line would end up inside the file it just wrote.
  lines.push('')
  lines.push('version: 2')
  lines.push('updates:')

  if (effective.includes('pip')) {
    lines.push('  # Python dependencies (pyproject.toml, uv.lock, requirements.txt).')
    lines.push('  - package-ecosystem: pip')
    lines.push('    directory: "' + directory + '"')
    lines.push('    schedule:')
    lines.push('      interval: ' + schedule)
    if (cooldown > 0) {
      lines.push('    # Supply-chain protection: do not adopt a release younger than')
      lines.push('    # ' + cooldown + ' days, so a compromised version is usually caught before it')
      lines.push('    # reaches this project.')
      lines.push('    cooldown:')
      lines.push('      default-days: ' + cooldown)
    }
    if (includeGrouping) {
      lines.push('    # One PR per update type instead of one PR per package.')
      lines.push('    groups:')
      lines.push('      dev-dependencies:')
      lines.push('        dependency-type: development')
      lines.push('        update-types: [minor, patch]')
      lines.push('      production-dependencies:')
      lines.push('        dependency-type: production')
      lines.push('        update-types: [patch]')
    }
  }

  if (effective.includes('github-actions')) {
    lines.push('')
    lines.push('  # The workflows themselves: an action pinned to an old tag is a supply-chain risk.')
    lines.push('  - package-ecosystem: github-actions')
    lines.push('    directory: "/"')
    lines.push('    schedule:')
    lines.push('      interval: ' + schedule)
    if (cooldown > 0) {
      lines.push('    cooldown:')
      lines.push('      default-days: ' + cooldown)
    }
    if (includeGrouping) {
      lines.push('    groups:')
      lines.push('      actions:')
      lines.push('        patterns: ["*"]')
      lines.push('        update-types: [minor, patch]')
    }
  }

  return lines.join('\n') + '\n'
}

/** Where the file goes, relative to the project root. */
export const DEPENDABOT_PATH = '.github/dependabot.yml'

/** What the caller still has to do after copying the file. */
export function dependabotNextSteps({ cooldownDays = 7 } = {}) {
  const steps = [
    'mkdir -p .github && copy the YAML to ' + DEPENDABOT_PATH,
    'commit it — Dependabot only reads the config on the default branch',
  ]
  if (cooldownDays > 0) {
    steps.push(
      'keep cooldown.default-days=' + cooldownDays + ' unless you accept the risk the skill warns about',
    )
  }
  return steps
}

/** Why each block is there. */
export function dependabotRationale(options = {}) {
  const cooldown = Number.isInteger(options.cooldownDays) ? options.cooldownDays : 7
  return [
    'Dependabot is GitHub-native: no service to run, and its PRs carry the changelog and '
    + 'compatibility notes a manual `uv lock --upgrade` does not.',
    'the pip ecosystem covers pyproject.toml / uv.lock, the github-actions ecosystem covers the '
    + 'workflow files themselves — an action left on an old tag is the same supply-chain risk as an '
    + 'old dependency.',
    'cooldown.default-days=' + cooldown + ' is the skill\'s supply-chain mitigation: newly published '
    + 'versions wait, so a malicious release is usually yanked before it is adopted here.',
    'grouping keeps minor/patch updates in one PR per dependency type, which is what makes a weekly '
    + 'schedule survivable instead of a PR avalanche.',
  ]
}
